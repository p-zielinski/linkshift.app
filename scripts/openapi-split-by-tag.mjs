import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const frontendRoot = resolve(repoRoot, 'frontend');
const requireFromFrontend = createRequire(resolve(frontendRoot, 'package.json'));
const { parse: parseYaml, stringify: stringifyYaml } = requireFromFrontend('yaml');

const DEFAULT_SOURCE = resolve(
  repoRoot,
  'shared',
  'docs',
  'openapi',
  'linkshift-api-keys.openapi.yaml',
);
const DEFAULT_OUTPUT_DIR = resolve(
  repoRoot,
  'shared',
  'docs',
  'openapi',
  'by-tag',
);

const HTTP_METHODS = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']);

function parseArgs(argv) {
  const args = {
    source: DEFAULT_SOURCE,
    outDir: DEFAULT_OUTPUT_DIR,
    format: 'json',
    clean: true,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === '--source') {
      args.source = resolve(repoRoot, argv[index + 1] ?? '');
      index += 1;
    } else if (token === '--out') {
      args.outDir = resolve(repoRoot, argv[index + 1] ?? '');
      index += 1;
    } else if (token === '--format') {
      args.format = String(argv[index + 1] ?? 'json').toLowerCase();
      index += 1;
    } else if (token === '--no-clean') {
      args.clean = false;
    } else if (token === '--help' || token === '-h') {
      printHelp();
      process.exit(0);
    }
  }

  if (!['json', 'yaml', 'both'].includes(args.format)) {
    throw new Error(`Unsupported --format "${args.format}". Use json, yaml, or both.`);
  }

  return args;
}

function printHelp() {
  console.log(`Usage: node scripts/openapi-split-by-tag.mjs [options]

Splits a monolithic OpenAPI document into one file per top-level tag.
Output is optimized for LLM ingestion (pretty-printed JSON by default).

After changing the source contract, run \`npm run docs:summaries:all\` to refresh
\`shared/docs-summaries/openapi/by-tag/*.openapi.summary.md\` (summaries are
generated by scripts/docs-summaries.mjs, not this split script).

Options:
  --source <path>   OpenAPI source file (default: shared/docs/openapi/linkshift-api-keys.openapi.yaml)
  --out <dir>       Output directory (default: shared/docs/openapi/by-tag)
  --format <type>   json | yaml | both (default: json)
  --no-clean        Do not delete existing files in the output directory first
  -h, --help        Show this help
`);
}

function slugifyTag(tagName) {
  return tagName
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function collectComponentRefs(node, refs = new Set()) {
  if (node === null || node === undefined) {
    return refs;
  }

  if (Array.isArray(node)) {
    for (const item of node) {
      collectComponentRefs(item, refs);
    }
    return refs;
  }

  if (typeof node !== 'object') {
    return refs;
  }

  if (typeof node.$ref === 'string' && node.$ref.startsWith('#/components/')) {
    refs.add(node.$ref);
  }

  for (const value of Object.values(node)) {
    collectComponentRefs(value, refs);
  }

  return refs;
}

function resolveComponentRefs(seedRefs, components) {
  const resolved = new Set(seedRefs);

  let changed = true;
  while (changed) {
    changed = false;
    for (const ref of [...resolved]) {
      const match = ref.match(/^#\/components\/([^/]+)\/([^/]+)$/);
      if (!match) {
        continue;
      }

      const [, section, name] = match;
      const fragment = components?.[section]?.[name];
      if (!fragment) {
        continue;
      }

      const nested = collectComponentRefs(fragment, new Set());
      for (const nestedRef of nested) {
        if (!resolved.has(nestedRef)) {
          resolved.add(nestedRef);
          changed = true;
        }
      }
    }
  }

  return resolved;
}

function pickComponents(components, refs) {
  const picked = {};

  for (const ref of refs) {
    const match = ref.match(/^#\/components\/([^/]+)\/([^/]+)$/);
    if (!match) {
      continue;
    }

    const [, section, name] = match;
    const value = components?.[section]?.[name];
    if (!value) {
      continue;
    }

    if (!picked[section]) {
      picked[section] = {};
    }
    picked[section][name] = value;
  }

  if (components?.securitySchemes) {
    picked.securitySchemes = { ...components.securitySchemes };
  }

  return picked;
}

function filterPathsForTag(paths, tagName) {
  const filtered = {};

  for (const [path, pathItem] of Object.entries(paths ?? {})) {
    if (!pathItem || typeof pathItem !== 'object') {
      continue;
    }

    const nextPathItem = {};
    let hasOperation = false;

    for (const [key, value] of Object.entries(pathItem)) {
      if (HTTP_METHODS.has(key)) {
        const operationTags = Array.isArray(value?.tags) ? value.tags.map(String) : [];
        if (operationTags.includes(tagName)) {
          nextPathItem[key] = value;
          hasOperation = true;
        }
        continue;
      }

      if (key === 'parameters' || key === 'summary' || key === 'description' || key === 'servers') {
        nextPathItem[key] = value;
      }
    }

    if (hasOperation) {
      filtered[path] = nextPathItem;
    }
  }

  return filtered;
}

function countOperations(paths) {
  let count = 0;
  for (const pathItem of Object.values(paths ?? {})) {
    for (const key of Object.keys(pathItem ?? {})) {
      if (HTTP_METHODS.has(key)) {
        count += 1;
      }
    }
  }
  return count;
}

function buildTagSpec(openapi, tagName, tagMeta) {
  const paths = filterPathsForTag(openapi.paths, tagName);
  const operationCount = countOperations(paths);

  const seedRefs = collectComponentRefs({
    paths,
    security: openapi.security,
  });

  const componentRefs = resolveComponentRefs(seedRefs, openapi.components ?? {});
  const components = pickComponents(openapi.components ?? {}, componentRefs);

  const tags = Array.isArray(openapi.tags)
    ? openapi.tags.filter((entry) => entry?.name === tagName)
    : tagMeta
      ? [tagMeta]
      : [{ name: tagName }];

  return {
    openapi: openapi.openapi,
    info: {
      ...openapi.info,
      title: `${openapi.info?.title ?? 'API'} — ${tagName}`,
      description: [
        typeof openapi.info?.description === 'string' ? openapi.info.description.trim() : '',
        '',
        `This document contains only operations tagged "${tagName}".`,
        tagMeta?.description ? `Tag scope: ${tagMeta.description}` : '',
      ]
        .filter(Boolean)
        .join('\n'),
    },
    servers: openapi.servers,
    security: openapi.security,
    tags,
    paths,
    components,
    'x-linkshift': {
      sourceTag: tagName,
      operationCount,
      generatedBy: 'scripts/openapi-split-by-tag.mjs',
    },
  };
}

function serializeDocument(document, format) {
  if (format === 'json') {
    return `${JSON.stringify(document, null, 2)}\n`;
  }

  return stringifyYaml(document, { lineWidth: 0 });
}

function writeOutputs({ outDir, slug, document, format }) {
  const formats = format === 'both' ? ['json', 'yaml'] : [format];
  const written = [];

  for (const fileFormat of formats) {
    const extension = fileFormat === 'json' ? 'json' : 'yaml';
    const filePath = resolve(outDir, `${slug}.openapi.${extension}`);
    writeFileSync(filePath, serializeDocument(document, fileFormat), 'utf8');
    written.push(filePath);
  }

  return written;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const openapiText = readFileSync(args.source, 'utf8');
  const openapi = parseYaml(openapiText);

  if (!openapi || typeof openapi !== 'object') {
    throw new Error(`Failed to parse OpenAPI document: ${args.source}`);
  }

  const tagEntries = Array.isArray(openapi.tags) ? openapi.tags : [];
  if (tagEntries.length === 0) {
    throw new Error('OpenAPI document has no top-level tags[] definitions.');
  }

  if (args.clean && existsSync(args.outDir)) {
    rmSync(args.outDir, { recursive: true, force: true });
  }
  mkdirSync(args.outDir, { recursive: true });

  const index = {
    source: args.source.replace(`${repoRoot}/`, ''),
    generatedAt: new Date().toISOString(),
    format: args.format,
    tags: [],
  };

  for (const tagMeta of tagEntries) {
    const tagName = String(tagMeta?.name ?? '').trim();
    if (!tagName) {
      continue;
    }

    const slug = slugifyTag(tagName);
    const document = buildTagSpec(openapi, tagName, tagMeta);
    const written = writeOutputs({
      outDir: args.outDir,
      slug,
      document,
      format: args.format,
    });

    index.tags.push({
      name: tagName,
      slug,
      description: tagMeta.description ?? '',
      operationCount: document['x-linkshift'].operationCount,
      files: written.map((filePath) => filePath.replace(`${repoRoot}/`, '')),
    });

    console.log(
      `${tagName}: ${document['x-linkshift'].operationCount} operations -> ${written
        .map((filePath) => filePath.replace(`${repoRoot}/`, ''))
        .join(', ')}`,
    );
  }

  const indexPath = resolve(args.outDir, 'index.json');
  writeFileSync(indexPath, `${JSON.stringify(index, null, 2)}\n`, 'utf8');
  console.log(`Wrote ${indexPath.replace(`${repoRoot}/`, '')}`);
  console.log(`Tags: ${index.tags.length}`);
}

main();
